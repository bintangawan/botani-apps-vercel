create or replace function public.save_plant_species(
  p_plant_id bigint,
  p_payload jsonb,
  p_morphology jsonb,
  p_taxonomy jsonb
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  saved_id bigint;
  parent_taxon_id bigint := null;
  saved_taxon_id bigint;
  rank_name text;
  rank_value public.taxon_rank;
begin
  if not public.can_manage_content() then
    raise exception 'Akses ditolak';
  end if;

  if p_plant_id is null then
    insert into public.plant_species (
      code, slug, local_name, scientific_name, author_name, group_type,
      cotyledon_type, description, habitat, benefits, image_path, status
    ) values (
      upper(p_payload ->> 'code'), p_payload ->> 'slug', trim(p_payload ->> 'local_name'),
      trim(p_payload ->> 'scientific_name'), nullif(trim(p_payload ->> 'author_name'), ''),
      (p_payload ->> 'group_type')::public.group_type,
      (p_payload ->> 'cotyledon_type')::public.cotyledon_type,
      nullif(trim(p_payload ->> 'description'), ''), nullif(trim(p_payload ->> 'habitat'), ''),
      nullif(trim(p_payload ->> 'benefits'), ''), nullif(p_payload ->> 'image_path', ''),
      (p_payload ->> 'status')::public.publication_status
    ) returning id into saved_id;
  else
    update public.plant_species set
      code = upper(p_payload ->> 'code'),
      slug = p_payload ->> 'slug',
      local_name = trim(p_payload ->> 'local_name'),
      scientific_name = trim(p_payload ->> 'scientific_name'),
      author_name = nullif(trim(p_payload ->> 'author_name'), ''),
      group_type = (p_payload ->> 'group_type')::public.group_type,
      cotyledon_type = (p_payload ->> 'cotyledon_type')::public.cotyledon_type,
      description = nullif(trim(p_payload ->> 'description'), ''),
      habitat = nullif(trim(p_payload ->> 'habitat'), ''),
      benefits = nullif(trim(p_payload ->> 'benefits'), ''),
      image_path = nullif(p_payload ->> 'image_path', ''),
      status = (p_payload ->> 'status')::public.publication_status
    where id = p_plant_id
    returning id into saved_id;

    if saved_id is null then
      raise exception 'Spesimen tidak ditemukan';
    end if;
  end if;

  insert into public.morphologies (
    species_id, root, stem, leaf, flower, fruit, seed, special_characteristics
  ) values (
    saved_id, nullif(trim(p_morphology ->> 'root'), ''), nullif(trim(p_morphology ->> 'stem'), ''),
    nullif(trim(p_morphology ->> 'leaf'), ''), nullif(trim(p_morphology ->> 'flower'), ''),
    nullif(trim(p_morphology ->> 'fruit'), ''), nullif(trim(p_morphology ->> 'seed'), ''),
    nullif(trim(p_morphology ->> 'special_characteristics'), '')
  )
  on conflict (species_id) do update set
    root = excluded.root, stem = excluded.stem, leaf = excluded.leaf,
    flower = excluded.flower, fruit = excluded.fruit, seed = excluded.seed,
    special_characteristics = excluded.special_characteristics;

  delete from public.species_taxa where species_id = saved_id;

  foreach rank_name in array array['kingdom', 'divisi', 'kelas', 'ordo', 'famili', 'genus', 'spesies']
  loop
    if nullif(trim(p_taxonomy ->> rank_name), '') is not null then
      rank_value := rank_name::public.taxon_rank;
      insert into public.taxa (parent_id, name, rank)
      values (parent_taxon_id, trim(p_taxonomy ->> rank_name), rank_value)
      on conflict (rank, name) do update
        set parent_id = coalesce(public.taxa.parent_id, excluded.parent_id)
      returning id into saved_taxon_id;

      insert into public.species_taxa (species_id, taxon_id)
      values (saved_id, saved_taxon_id)
      on conflict do nothing;
      parent_taxon_id := saved_taxon_id;
    end if;
  end loop;

  return saved_id;
end;
$$;

create or replace function public.save_learning_module(
  p_module_id bigint,
  p_payload jsonb,
  p_lessons jsonb,
  p_species_ids bigint[]
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
  saved_id bigint;
  lesson jsonb;
begin
  if not public.can_manage_content() then
    raise exception 'Akses ditolak';
  end if;

  if jsonb_array_length(p_lessons) = 0 then
    raise exception 'Minimal satu subbab harus tersedia';
  end if;

  if p_module_id is null then
    insert into public.learning_modules (
      title, slug, description, module_order, estimated_minutes,
      chapter_summary, source_file, status
    ) values (
      trim(p_payload ->> 'title'), p_payload ->> 'slug', coalesce(trim(p_payload ->> 'description'), ''),
      (p_payload ->> 'module_order')::integer, (p_payload ->> 'estimated_minutes')::integer,
      coalesce(p_payload -> 'chapter_summary', '[]'::jsonb), nullif(p_payload ->> 'source_file', ''),
      (p_payload ->> 'status')::public.publication_status
    ) returning id into saved_id;
  else
    update public.learning_modules set
      title = trim(p_payload ->> 'title'),
      slug = p_payload ->> 'slug',
      description = coalesce(trim(p_payload ->> 'description'), ''),
      module_order = (p_payload ->> 'module_order')::integer,
      estimated_minutes = (p_payload ->> 'estimated_minutes')::integer,
      chapter_summary = coalesce(p_payload -> 'chapter_summary', '[]'::jsonb),
      source_file = nullif(p_payload ->> 'source_file', ''),
      status = (p_payload ->> 'status')::public.publication_status
    where id = p_module_id
    returning id into saved_id;

    if saved_id is null then
      raise exception 'Bab pembelajaran tidak ditemukan';
    end if;
  end if;

  delete from public.learning_lessons where module_id = saved_id;

  for lesson in select value from jsonb_array_elements(p_lessons)
  loop
    insert into public.learning_lessons (
      module_id, source_id, title, slug, content, content_format,
      key_points, source_sections, lesson_order
    ) values (
      saved_id, nullif(lesson ->> 'source_id', ''), trim(lesson ->> 'title'),
      lesson ->> 'slug', lesson ->> 'content', coalesce(lesson ->> 'content_format', 'markdown'),
      coalesce(lesson -> 'key_points', '[]'::jsonb), coalesce(lesson -> 'source_sections', '[]'::jsonb),
      (lesson ->> 'lesson_order')::integer
    );
  end loop;

  delete from public.module_species where module_id = saved_id;
  insert into public.module_species (module_id, species_id)
  select saved_id, species_id
  from unnest(coalesce(p_species_ids, array[]::bigint[])) as species_id;

  return saved_id;
end;
$$;

create or replace function public.start_quiz_attempt(p_quiz_id bigint)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
  existing_id bigint;
begin
  if public.current_user_role() <> 'mahasiswa' then
    raise exception 'Hanya mahasiswa aktif yang dapat mengerjakan kuis';
  end if;

  if not exists (
    select 1 from public.quizzes q
    where q.id = p_quiz_id and q.status = 'published'
      and exists (select 1 from public.questions qn where qn.quiz_id = q.id)
  ) then
    raise exception 'Kuis belum tersedia atau belum memiliki soal';
  end if;

  select id into existing_id
  from public.quiz_attempts
  where user_id = auth.uid() and quiz_id = p_quiz_id and completed_at is null
  limit 1;

  if existing_id is not null then
    return existing_id;
  end if;

  insert into public.quiz_attempts (user_id, quiz_id)
  values (auth.uid(), p_quiz_id)
  returning id into existing_id;

  return existing_id;
end;
$$;

create or replace function public.submit_quiz_attempt(p_attempt_id bigint, p_answers jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  attempt_row public.quiz_attempts%rowtype;
  question_row public.questions%rowtype;
  selected_id bigint;
  answer_text text;
  correct boolean;
  total_weight integer := 0;
  earned_weight integer := 0;
  correct_count integer := 0;
  final_score integer := 0;
begin
  select * into attempt_row
  from public.quiz_attempts
  where id = p_attempt_id
  for update;

  if attempt_row.id is null or attempt_row.user_id <> auth.uid() then
    raise exception 'Percobaan kuis tidak ditemukan';
  end if;

  if attempt_row.completed_at is not null then
    raise exception 'Percobaan kuis sudah diselesaikan';
  end if;

  for question_row in
    select * from public.questions where quiz_id = attempt_row.quiz_id order by id
  loop
    total_weight := total_weight + question_row.score_weight;
    selected_id := null;
    answer_text := nullif(trim(p_answers ->> question_row.id::text), '');
    correct := false;

    if question_row.question_type in ('pilihan_ganda', 'multiple_choice', 'true_false')
       and answer_text ~ '^[0-9]+$' then
      selected_id := answer_text::bigint;
      select exists (
        select 1
        from public.question_options qo
        join public.question_keys qk on qk.correct_option_id = qo.id
        where qo.id = selected_id
          and qo.question_id = question_row.id
          and qk.question_id = question_row.id
      ) into correct;
    end if;

    if correct then
      earned_weight := earned_weight + question_row.score_weight;
      correct_count := correct_count + 1;
    end if;

    insert into public.quiz_answers (
      attempt_id, question_id, selected_option_id, essay_answer, is_correct
    ) values (
      attempt_row.id, question_row.id, selected_id,
      case when question_row.question_type = 'esai' then answer_text else null end,
      correct
    )
    on conflict (attempt_id, question_id) do update set
      selected_option_id = excluded.selected_option_id,
      essay_answer = excluded.essay_answer,
      is_correct = excluded.is_correct;
  end loop;

  if total_weight > 0 then
    final_score := round((earned_weight::numeric / total_weight::numeric) * 100)::integer;
  end if;

  update public.quiz_attempts
  set completed_at = now(), score = final_score, total_correct = correct_count
  where id = attempt_row.id;

  return jsonb_build_object(
    'attempt_id', attempt_row.id,
    'score', final_score,
    'total_correct', correct_count
  );
end;
$$;

create or replace function public.get_quiz_result(p_attempt_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  attempt_row public.quiz_attempts%rowtype;
  quiz_row public.quizzes%rowtype;
  module_row public.learning_modules%rowtype;
  question_details jsonb;
begin
  select * into attempt_row from public.quiz_attempts where id = p_attempt_id;

  if attempt_row.id is null
     or (attempt_row.user_id <> auth.uid() and not public.can_manage_content()) then
    raise exception 'Hasil kuis tidak ditemukan';
  end if;

  if attempt_row.completed_at is null then
    raise exception 'Kuis belum diselesaikan';
  end if;

  select * into quiz_row from public.quizzes where id = attempt_row.quiz_id;
  select * into module_row from public.learning_modules where id = quiz_row.module_id;

  select coalesce(jsonb_agg(detail.item order by detail.question_id), '[]'::jsonb)
  into question_details
  from (
    select
      qn.id as question_id,
      jsonb_build_object(
        'question', to_jsonb(qn),
        'options', coalesce((
          select jsonb_agg(to_jsonb(qo) order by qo.id)
          from public.question_options qo
          where qo.question_id = qn.id
        ), '[]'::jsonb),
        'answer', (
          select to_jsonb(qa)
          from public.quiz_answers qa
          where qa.attempt_id = attempt_row.id and qa.question_id = qn.id
        ),
        'correct_option_id', (
          select qk.correct_option_id
          from public.question_keys qk
          where qk.question_id = qn.id
        )
      ) as item
    from public.questions qn
    where qn.quiz_id = quiz_row.id
  ) as detail;

  return jsonb_build_object(
    'attempt', to_jsonb(attempt_row),
    'quiz', to_jsonb(quiz_row),
    'module', to_jsonb(module_row),
    'questions', question_details
  );
end;
$$;

